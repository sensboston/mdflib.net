// Projects the MdfLibrary facade into the package signature baseline api/public-api.txt (the port of
// tools/mdflibrary/public_api.py). Since 1.0 the MdfLibrary namespace is the whole public surface of MdfLibrary.Managed.
// The member set comes from api/mdflibrary-api-baseline.txt; modifiers are read from the declarations in
// src/MdfLib/MdfLibrary/*.cs (an implicit implementation of an interface member is `virtual final` in the compiled
// assembly whether or not the class is sealed). A declaration the projection cannot place stops it; nothing is guessed.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace MdfLib.Ci
{
    internal static class PublicApi
    {
        private const string Namespace = "MdfLibrary";
        private const string Public = "6";
        private const string Output = "api/public-api.txt";
        private const string Baseline = "api/mdflibrary-api-baseline.txt";
        private const string FacadeFolder = "src/MdfLib/MdfLibrary";

        private const string Header =
            "# Public API baseline of MdfLibrary.Managed 1.0.0: the MdfLibrary namespace only (the engine MdfLib.* is internal).\n"
            + "# Generated by tools/MdfLib.Ci (public-api) from api/mdflibrary-api-baseline.txt and the facade declarations;\n"
            + "# regenerate with `dotnet run --project tools/MdfLib.Ci -- public-api --write`, never by hand.\n"
            + "# Grammar: T|type|base|abstract|sealed  I|type|interface  M|type|name|return|access|static|virtual|final|params\n"
            + "#          P|type|name|type|get|set  F|type|name|type|access|static|value\n"
            + "# Compared by runtime reflection (tests/MdfLib.Tests/AssemblyContractTests.cs) and by the metadata-only package\n"
            + "# audit (tools/MdfLib.PackageAudit). Parameters are `type name=!` (none is optional in the 1.0 facade).\n";

        private static readonly Dictionary<string, string> ClrKeywords = new Dictionary<string, string>
        {
            { "void", "System.Void" }, { "bool", "System.Boolean" }, { "byte", "System.Byte" }, { "sbyte", "System.SByte" },
            { "char", "System.Char" }, { "short", "System.Int16" }, { "ushort", "System.UInt16" }, { "int", "System.Int32" },
            { "uint", "System.UInt32" }, { "long", "System.Int64" }, { "ulong", "System.UInt64" }, { "float", "System.Single" },
            { "double", "System.Double" }, { "decimal", "System.Decimal" }, { "string", "System.String" }, { "object", "System.Object" },
        };

        private static readonly Regex HeaderPattern = new Regex("^    public ((?:static |sealed |abstract )*)(class|interface|enum|struct) (\\w+)\\s*(?::\\s*([^{]+?))?\\s*(?:\\{.*)?$");
        private static readonly Regex DelegatePattern = new Regex("^    public delegate \\S+ (\\w+)\\(");

        private sealed class Declared
        {
            public string Kind;
            public bool Static;
            public bool Sealed;
            public bool Abstract;
            public List<string> Interfaces = new List<string>();
        }

        /// <summary>A baseline row is a list of fields; the first is its kind letter.</summary>
        private static List<string[]> ReadBaseline()
        {
            List<string[]> rows = new List<string[]>();
            foreach (string line in Shell.ReadText(Shell.Under(Baseline)).Split('\n'))
            {
                if (line.Length > 0 && !line.StartsWith("#", StringComparison.Ordinal))
                {
                    rows.Add(line.Split('|'));
                }
            }
            return rows;
        }

        /// <summary>Splits on a separator that is not nested inside angle brackets or square brackets.</summary>
        private static List<string> SplitTop(string text, char separator)
        {
            List<string> parts = new List<string>();
            int depth = 0;
            StringBuilder current = new StringBuilder();
            foreach (char character in text)
            {
                if (character == '<' || character == '[')
                {
                    depth++;
                }
                else if (character == '>' || character == ']')
                {
                    depth--;
                }
                if (character == separator && depth == 0)
                {
                    parts.Add(current.ToString());
                    current.Clear();
                }
                else
                {
                    current.Append(character);
                }
            }
            if (current.ToString().Trim().Length > 0)
            {
                parts.Add(current.ToString());
            }
            return parts.Select(part => part.Trim()).Where(part => part.Length > 0).ToList();
        }

        /// <summary>A baseline type token as the CLR FullName: System.Byte[] and generic types with the backtick arity.</summary>
        private static string Clr(string token)
        {
            token = token.Trim();
            if (token.EndsWith("[]", StringComparison.Ordinal))
            {
                return Clr(token.Substring(0, token.Length - 2)) + "[]";
            }
            if (token.StartsWith("ref ", StringComparison.Ordinal))
            {
                return Clr(token.Substring(4)) + "&";
            }
            Match generic = Regex.Match(token, "^([\\w.]+)<(.*)>$");
            if (generic.Success)
            {
                List<string> arguments = SplitTop(generic.Groups[2].Value, ';');
                return generic.Groups[1].Value + "`" + arguments.Count + "[" + string.Join(",", arguments.Select(Clr)) + "]";
            }
            string keyword;
            return ClrKeywords.TryGetValue(token, out keyword) ? keyword : token;
        }

        /// <summary>A baseline parameter list as ApiSurface writes it: `T&amp; name=!;U other=!`.</summary>
        private static string Parameters(string text)
        {
            if (text.Trim().Length == 0)
            {
                return "";
            }
            List<string> output = new List<string>();
            foreach (string part in SplitTop(text, ';'))
            {
                bool reference = part.StartsWith("ref ", StringComparison.Ordinal);
                string body = reference ? part.Substring(4) : part;
                int cut = body.LastIndexOf(' ');
                if (cut < 0)
                {
                    throw new PublicApiError("parameter without a name: " + part);
                }
                output.Add(Clr(body.Substring(0, cut)) + (reference ? "&" : "") + " " + body.Substring(cut + 1) + "=!");
            }
            return string.Join(";", output);
        }

        private sealed class PublicApiError : Exception
        {
            public PublicApiError(string message) : base(message)
            {
            }
        }

        /// <summary>The modifiers, base list and interface list of every public facade type, read from the declarations.</summary>
        private static Dictionary<string, Declared> DeclaredTypes()
        {
            Dictionary<string, Declared> found = new Dictionary<string, Declared>();
            string folder = Shell.Under(FacadeFolder);
            foreach (string path in Directory.GetFiles(folder, "*.cs").OrderBy(p => Path.GetFileName(p), StringComparer.Ordinal))
            {
                foreach (string line in Shell.SplitLines(Shell.ReadText(path)))
                {
                    Match match = HeaderPattern.Match(line);
                    if (match.Success)
                    {
                        List<string> modifiers = match.Groups[1].Value.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries).ToList();
                        List<string> bases = match.Groups[4].Success
                            ? match.Groups[4].Value.Split(',').Select(b => b.Trim()).Where(b => b.Length > 0).ToList()
                            : new List<string>();
                        found[match.Groups[3].Value] = new Declared
                        {
                            Kind = match.Groups[2].Value,
                            Static = modifiers.Contains("static"),
                            Sealed = modifiers.Contains("sealed"),
                            Abstract = modifiers.Contains("abstract"),
                            Interfaces = bases.Where(b => Regex.IsMatch(b, "^I[A-Z]")).ToList(),
                        };
                        continue;
                    }
                    match = DelegatePattern.Match(line);
                    if (match.Success)
                    {
                        found[match.Groups[1].Value] = new Declared { Kind = "delegate", Sealed = true };
                    }
                }
            }
            return found;
        }

        private static string Flag(bool value)
        {
            return value ? "true" : "false";
        }

        /// <summary>The projected lines of the baseline, sorted by their UTF-8 bytes.</summary>
        internal static List<string> Project()
        {
            List<string[]> rows = ReadBaseline();
            Dictionary<string, Declared> declared = DeclaredTypes();
            Dictionary<string, string[]> types = new Dictionary<string, string[]>();
            foreach (string[] row in rows.Where(r => r[0] == "T"))
            {
                types[row[1].Split(new[] { '.' }, 2)[1]] = row;
            }
            List<string> typeNames = types.Keys.OrderBy(k => k, StringComparer.Ordinal).ToList();
            List<string> declaredNames = declared.Keys.OrderBy(k => k, StringComparer.Ordinal).ToList();
            List<string> difference = typeNames.Union(declaredNames).Except(typeNames.Intersect(declaredNames)).OrderBy(k => k, StringComparer.Ordinal).ToList();
            if (difference.Count > 0)
            {
                throw new PublicApiError("facade declarations and the baseline name different types: " + string.Join(", ", difference));
            }

            // Members of each interface, for the implicit implementations of the classes that implement it.
            Dictionary<string, HashSet<string>> interfaceMethods = new Dictionary<string, HashSet<string>>();
            Dictionary<string, HashSet<string>> interfaceProperties = new Dictionary<string, HashSet<string>>();
            foreach (string[] row in rows)
            {
                string shortName = row.Length > 1 ? row[1].Split(new[] { '.' }, 2)[1] : null;
                if (row[0] == "M" && declared[shortName].Kind == "interface")
                {
                    Add(interfaceMethods, row[1], row[2] + "\u0001" + (row.Length > 5 ? Parameters(row[5]) : ""));
                }
                if (row[0] == "P" && declared[shortName].Kind == "interface")
                {
                    Add(interfaceProperties, row[1], row[2]);
                }
            }

            List<string> lines = new List<string>();
            foreach (KeyValuePair<string, Declared> pair in declared)
            {
                string owner = pair.Key;
                Declared info = pair.Value;
                string full = Namespace + "." + owner;
                string bas;
                string abstractFlag;
                string sealedFlag;
                if (info.Kind == "interface")
                {
                    bas = "-";
                    abstractFlag = "true";
                    sealedFlag = "false";
                }
                else if (info.Kind == "enum")
                {
                    bas = "System.Enum";
                    abstractFlag = "false";
                    sealedFlag = "true";
                }
                else if (info.Kind == "delegate")
                {
                    bas = "System.MulticastDelegate";
                    abstractFlag = "false";
                    sealedFlag = "true";
                }
                else
                {
                    // The baseline's fourth column lists implemented interfaces, never a base class (checked here, not guessed).
                    string listed = types[owner][3];
                    if (listed != "-" && !Regex.IsMatch(listed, "^" + Regex.Escape(Namespace) + "\\.I[A-Z]\\w*$"))
                    {
                        throw new PublicApiError("facade type " + owner + " lists a base class in the baseline: " + listed);
                    }
                    bas = "System.Object";
                    abstractFlag = Flag(info.Abstract || info.Static);
                    sealedFlag = Flag(info.Sealed || info.Static);
                }
                lines.Add("T|" + full + "|" + bas + "|" + abstractFlag + "|" + sealedFlag);
                foreach (string contract in info.Interfaces)
                {
                    lines.Add("I|" + full + "|" + Namespace + "." + contract);
                }
            }

            // (virtual, final) of a method of `owner`: an interface member is abstract virtual; an implicit implementation
            // of an interface member is virtual final.
            Func<string, string, string, KeyValuePair<string, string>> virtualOf = (owner, name, parameters) =>
            {
                Declared info = declared[owner.Split(new[] { '.' }, 2)[1]];
                if (info.Kind == "interface")
                {
                    return new KeyValuePair<string, string>("true", "false");
                }
                foreach (string contract in info.Interfaces)
                {
                    HashSet<string> methods = Lookup(interfaceMethods, Namespace + "." + contract);
                    HashSet<string> properties = Lookup(interfaceProperties, Namespace + "." + contract);
                    bool isMethod = methods.Contains(name + "\u0001" + parameters);
                    bool isProperty = properties.Contains(name)
                        || ((name.StartsWith("get_", StringComparison.Ordinal) || name.StartsWith("set_", StringComparison.Ordinal))
                            && properties.Contains(name.Substring(4)));
                    if (isMethod || isProperty)
                    {
                        return new KeyValuePair<string, string>("true", "true");
                    }
                }
                return new KeyValuePair<string, string>("false", "false");
            };

            foreach (string[] row in rows)
            {
                string kind = row[0];
                string owner = row[1];
                switch (kind)
                {
                    case "T":
                        break;
                    case "C":
                        lines.Add("M|" + owner + "|.ctor|System.Void|" + Public + "|false|false|false|" + Parameters(row[2]));
                        break;
                    case "M":
                    {
                        string parameters = row.Length > 5 ? Parameters(row[5]) : "";
                        bool isStatic = row.Length > 4 && row[4] == "static";
                        KeyValuePair<string, string> flags = virtualOf(owner, row[2], parameters);
                        lines.Add("M|" + owner + "|" + row[2] + "|" + Clr(row[3]) + "|" + Public + "|" + Flag(isStatic) + "|" + flags.Key + "|" + flags.Value + "|" + parameters);
                        break;
                    }
                    case "P":
                    {
                        bool isStatic = row[4] == "static";
                        string accessors = row[5];
                        bool getter = accessors.Contains("get;");
                        bool setter = accessors.Contains("set;");
                        lines.Add("P|" + owner + "|" + row[2] + "|" + Clr(row[3]) + "|" + (getter ? "get" : "") + (setter ? "set" : ""));
                        if (getter)
                        {
                            KeyValuePair<string, string> flags = virtualOf(owner, "get_" + row[2], "");
                            lines.Add("M|" + owner + "|get_" + row[2] + "|" + Clr(row[3]) + "|" + Public + "|" + Flag(isStatic) + "|" + flags.Key + "|" + flags.Value + "|");
                        }
                        if (setter)
                        {
                            KeyValuePair<string, string> flags = virtualOf(owner, "set_" + row[2], "");
                            lines.Add("M|" + owner + "|set_" + row[2] + "|System.Void|" + Public + "|" + Flag(isStatic) + "|" + flags.Key + "|" + flags.Value + "|" + Clr(row[3]) + " value=!");
                        }
                        break;
                    }
                    case "X":
                    {
                        // X|type|Item|type|static|accessors|params
                        bool isStatic = row[4] == "static";
                        string accessors = row[5];
                        string parameters = Parameters(row[6]);
                        bool getter = accessors.Contains("get;");
                        bool setter = accessors.Contains("set;");
                        lines.Add("P|" + owner + "|Item|" + Clr(row[3]) + "|" + (getter ? "get" : "") + (setter ? "set" : ""));
                        if (getter)
                        {
                            KeyValuePair<string, string> flags = virtualOf(owner, "get_Item", parameters);
                            lines.Add("M|" + owner + "|get_Item|" + Clr(row[3]) + "|" + Public + "|" + Flag(isStatic) + "|" + flags.Key + "|" + flags.Value + "|" + parameters);
                        }
                        if (setter)
                        {
                            KeyValuePair<string, string> flags = virtualOf(owner, "set_Item", "");
                            lines.Add("M|" + owner + "|set_Item|System.Void|" + Public + "|" + Flag(isStatic) + "|" + flags.Key + "|" + flags.Value + "|"
                                + (parameters.Length > 0 ? parameters + ";" : "") + Clr(row[3]) + " value=!");
                        }
                        break;
                    }
                    case "E":
                        foreach (string accessor in new[] { "add_", "remove_" })
                        {
                            lines.Add("M|" + owner + "|" + accessor + row[2] + "|System.Void|" + Public + "|false|false|false|" + Clr(row[3]) + " value=!");
                        }
                        break;
                    case "F":
                        lines.Add("F|" + owner + "|" + row[2] + "|" + Clr(row[3]) + "|" + Public + "|true|" + row[4]);
                        break;
                    case "V":
                        lines.Add("F|" + owner + "|" + row[2] + "|" + owner + "|" + Public + "|true|" + row[3]);
                        break;
                    case "G":
                    {
                        string parameters = Parameters(row[3]);
                        string ret = Clr(row[2]);
                        string begin = (parameters.Length > 0 ? parameters + ";" : "") + "System.AsyncCallback callback=!;System.Object object=!";
                        lines.Add("M|" + owner + "|.ctor|System.Void|" + Public + "|false|false|false|System.Object object=!;System.IntPtr method=!");
                        lines.Add("M|" + owner + "|Invoke|" + ret + "|" + Public + "|false|true|false|" + parameters);
                        lines.Add("M|" + owner + "|BeginInvoke|System.IAsyncResult|" + Public + "|false|true|false|" + begin);
                        lines.Add("M|" + owner + "|EndInvoke|" + ret + "|" + Public + "|false|true|false|System.IAsyncResult result=!");
                        break;
                    }
                    default:
                        throw new PublicApiError("unknown baseline row: " + string.Join("|", row));
                }
            }

            // Enum value__: the compiler's instance field of the underlying type, public in the metadata.
            foreach (KeyValuePair<string, string[]> pair in types)
            {
                if (declared[pair.Key].Kind == "enum")
                {
                    lines.Add("F|" + Namespace + "." + pair.Key + "|value__|" + pair.Value[3] + "|" + Public + "|false|!");
                }
            }
            return lines.Distinct().OrderBy(line => line, StringComparer.Ordinal).ToList();
        }

        private static void Add(Dictionary<string, HashSet<string>> map, string key, string value)
        {
            HashSet<string> set;
            if (!map.TryGetValue(key, out set))
            {
                set = new HashSet<string>();
                map[key] = set;
            }
            set.Add(value);
        }

        private static HashSet<string> Lookup(Dictionary<string, HashSet<string>> map, string key)
        {
            HashSet<string> set;
            return map.TryGetValue(key, out set) ? set : new HashSet<string>();
        }

        /// <summary>The check or write of api/public-api.txt; returns the exit code.</summary>
        public static int Run(string[] args)
        {
            bool write = args.Contains("--write");
            bool check = args.Contains("--check");
            if (write == check)
            {
                Console.Error.WriteLine("usage: public-api --write | --check");
                return 2;
            }
            string text;
            try
            {
                text = Header + string.Join("\n", Project()) + "\n";
            }
            catch (PublicApiError error)
            {
                Console.Error.WriteLine("public api projection failed: " + error.Message);
                return 2;
            }
            string path = Shell.Under(Output);
            if (write)
            {
                Shell.WriteText(path, text);
                Console.Out.WriteLine("public api: wrote " + (text.Split('\n').Length - Header.Split('\n').Length) + " entries to " + Path.GetFileName(path));
                return 0;
            }
            string current = File.Exists(path) ? Shell.ReadText(path) : "";
            if (current != text)
            {
                Console.Error.WriteLine("public api: api/public-api.txt differs from the projection; run --write");
                return 1;
            }
            Console.Out.WriteLine("public api: api/public-api.txt matches the facade projection");
            return 0;
        }
    }
