using System.Text;
using MdfLib;

namespace MdfScope;

/// <summary>
/// Writes a synthetic ten-minute drive: vehicle signals at 100 Hz, powertrain at 10 Hz and a 2 kHz
/// vibration channel (1.2 million samples), with gear and brake as value-to-text channels, three
/// event markers and a small attachment. Everything is generated; no real recording is involved.
/// </summary>
public static class DemoFile
{
    const double Duration = 600;

    public static void Write(string path)
    {
        var options = new MdfWriterOptions
        {
            Version = "4.10",
            Comment = "Synthetic test drive generated by MdfScope",
            Author = "MdfScope",
            Project = "Demo measurement",
            Subject = "Urban and highway drive",
            ToolIdentifier = "MdfScope",
            ToolVendor = "mdflib.net",
            ToolVersion = "0.1",
            CompressData = true,
            StartTimeNanoseconds = (ulong)(new DateTimeOffset(2026, 6, 12, 9, 30, 0, TimeSpan.Zero).ToUnixTimeMilliseconds() * 1_000_000L),
        };

        var drive = Simulate(100);
        using var stream = new FileStream(path, FileMode.Create, FileAccess.ReadWrite, FileShare.None);
        using var writer = MdfWriter.Create(stream, leaveOpen: true, options: options);

        // Vehicle, 100 Hz
        int vehicle = 0;
        writer.SetChannelGroupName(vehicle, "Vehicle");
        writer.AddChannel(vehicle, Master());
        writer.AddChannel(vehicle, Float("VehicleSpeed", "km/h", "Speed over ground"));
        writer.AddChannel(vehicle, Float("EngineSpeed", "rpm", "Crankshaft speed"));
        writer.AddChannel(vehicle, Float("AcceleratorPedal", "%", "Accelerator pedal position"));
        writer.AddChannel(vehicle, Enum("Gear", "Selected gear", ["N", "1", "2", "3", "4", "5", "6"]));
        writer.AddChannel(vehicle, Enum("BrakeSwitch", "Brake pedal switch", ["Released", "Pressed"]));
        writer.AddChannel(vehicle, Float("SteeringAngle", "deg", "Steering wheel angle"));
        writer.AddChannel(vehicle, Float("LongitudinalAccel", "m/s²", "Longitudinal acceleration"));
        writer.AddChannel(vehicle, Float("LateralAccel", "m/s²", "Lateral acceleration"));

        // Powertrain, 10 Hz
        int powertrain = writer.AddChannelGroup("Powertrain");
        writer.AddChannel(powertrain, Master());
        writer.AddChannel(powertrain, Float("CoolantTemperature", "°C", "Engine coolant temperature"));
        writer.AddChannel(powertrain, Float("OilPressure", "bar", "Engine oil pressure"));
        writer.AddChannel(powertrain, Float("BatteryVoltage", "V", "12 V system voltage"));
        writer.AddChannel(powertrain, Float("FuelLevel", "%", "Fuel tank level"));

        // Vibration, 2 kHz
        int vibration = writer.AddChannelGroup("Vibration");
        writer.AddChannel(vibration, Master());
        writer.AddChannel(vibration, Float("SeatRailAccelZ", "g", "Vertical acceleration at the seat rail"));

        writer.AddAttachment(new MdfAttachmentDefinition
        {
            FileName = "test-notes.txt",
            MimeType = "text/plain",
            Comment = "Driver notes",
            Data = Encoding.UTF8.GetBytes("Dry road, 21 °C, one driver, tyre pressure 2.4 bar.\n"),
            Compress = true,
        });
        foreach (var (time, name) in drive.Events)
        {
            writer.AddEvent(new MdfEventDefinition
            {
                Name = name,
                Type = MdfEventType.Marker,
                SyncType = MdfEventSyncType.Time,
                SyncBaseValue = (long)Math.Round(time * 1000),
                SyncFactor = 0.001,
            });
        }

        writer.StartMeasurement();

        var rng = new Random(7);
        var row = new MdfSampleValue[9];
        for (int i = 0; i < drive.Count; i++)
        {
            double t = i / 100.0;
            row[0] = F(t);
            row[1] = F(drive.Speed[i]);
            row[2] = F(drive.Rpm[i]);
            row[3] = F(drive.Pedal[i]);
            row[4] = MdfSampleValue.FromUnsigned((ulong)drive.Gear[i]);
            row[5] = MdfSampleValue.FromUnsigned(drive.Brake[i] ? 1UL : 0UL);
            row[6] = F(drive.Steering[i]);
            row[7] = F(drive.LongAccel[i]);
            row[8] = F(drive.LatAccel[i]);
            writer.SaveSample(vehicle, row);
        }

        var slow = new MdfSampleValue[5];
        double coolant = 24, fuel = 78;
        for (int i = 0; i < Duration * 10; i++)
        {
            double t = i / 10.0;
            int k = Math.Min(drive.Count - 1, i * 10);
            coolant += (90 + drive.Rpm[k] / 900 - coolant) * 0.0035;
            fuel -= 0.0004 + drive.Pedal[k] * 0.00002;
            slow[0] = F(t);
            slow[1] = F(coolant + Noise(rng, 0.05));
            slow[2] = F(1.2 + drive.Rpm[k] / 1500 + Noise(rng, 0.03));
            slow[3] = F((drive.Rpm[k] > 500 ? 14.1 : 12.4) - drive.Pedal[k] * 0.004 + Noise(rng, 0.02));
            slow[4] = F(fuel);
            writer.SaveSample(powertrain, slow);
        }

        var fast = new MdfSampleValue[2];
        for (int i = 0; i < Duration * 2000; i++)
        {
            double t = i / 2000.0;
            int k = Math.Min(drive.Count - 1, i / 20);
            double v = drive.Speed[k] / 3.6;
            double engine = drive.Rpm[k] / 60;
            double z = 0.02 * Math.Sin(2 * Math.PI * engine * 2 * t)
                       + 0.004 * v * Math.Sin(2 * Math.PI * 11.5 * t)
                       + Noise(rng, 0.006 + v * 0.0009);
            if (drive.Bump(t)) z += 0.35 * Math.Exp(-((t % 1) * 18)) * Math.Sin(2 * Math.PI * 9 * t);
            fast[0] = F(t);
            fast[1] = F(z);
            writer.SaveSample(vibration, fast);
        }

        writer.StopMeasurement();
        writer.FinalizeMeasurement();
    }

    static MdfSampleValue F(double v) => MdfSampleValue.FromFloatingPoint(v);

    static double Noise(Random rng, double scale) => (rng.NextDouble() + rng.NextDouble() - 1) * scale;

    static MdfChannelDefinition Master() => new()
    {
        Name = "time", Unit = "s", ValueKind = MdfValueKind.FloatingPoint, BitCount = 64, IsMaster = true,
    };

    static MdfChannelDefinition Float(string name, string unit, string comment) => new()
    {
        Name = name, Unit = unit, ValueKind = MdfValueKind.FloatingPoint, BitCount = 32,
    };

    static MdfChannelDefinition Enum(string name, string comment, string[] texts) => new()
    {
        Name = name, ValueKind = MdfValueKind.UnsignedInteger, BitCount = 8,
        Conversion = MdfConversionDefinition.ValueToText(
            Enumerable.Range(0, texts.Length).Select(i => (double)i).ToArray(), texts, "invalid"),
    };

    sealed class Drive(int count)
    {
        public int Count = count;
        public double[] Speed = new double[count], Rpm = new double[count], Pedal = new double[count];
        public double[] Steering = new double[count], LongAccel = new double[count], LatAccel = new double[count];
        public int[] Gear = new int[count];
        public bool[] Brake = new bool[count];
        public List<(double Time, string Name)> Events = new();
        public List<double> Bumps = new();

        public bool Bump(double t) => Bumps.Any(b => t >= b && t < b + 1);
    }

    /// <summary>A speed profile from target speeds, a simple gearbox and a driver who follows it.</summary>
    static Drive Simulate(int rate)
    {
        int n = (int)(Duration * rate);
        var d = new Drive(n);
        // (time s, target km/h)
        (double T, double V)[] plan =
        [
            (0, 0), (8, 0), (25, 48), (45, 50), (55, 0), (70, 0), (95, 62), (130, 58), (150, 30), (165, 52),
            (190, 0), (205, 0), (240, 95), (300, 118), (360, 125), (390, 105), (420, 128), (470, 80),
            (495, 52), (520, 50), (540, 20), (555, 35), (580, 0), (600, 0),
        ];
        double[] ratios = [0, 13.2, 8.1, 5.6, 4.3, 3.5, 2.9];
        double v = 0, prevV = 0, heading = 0;
        int gear = 0;
        var rng = new Random(11);
        bool braking = false;
        double accel = 0, pedal = 0;

        for (int i = 0; i < n; i++)
        {
            double t = i / (double)rate;
            int s = Array.FindLastIndex(plan, p => p.T <= t);
            var a = plan[s];
            var b = plan[Math.Min(s + 1, plan.Length - 1)];
            double target = b.T > a.T ? a.V + (b.V - a.V) * Math.Clamp((t - a.T) / (b.T - a.T), 0, 1) : a.V;
            target += 1.2 * Math.Sin(t * 0.11) + 0.5 * Math.Sin(t * 0.29);
            target = Math.Max(0, a.V == 0 && b.V == 0 ? 0 : target);

            double error = target - v;
            double wantedAccel = Math.Clamp(error * 0.6, -7.5, 2.8);
            accel += (wantedAccel - accel) * 0.04;
            v = Math.Max(0, v + accel * 3.6 / rate);
            double longAccel = (v - prevV) / 3.6 * rate;
            prevV = v;

            bool brake = accel < -0.8;
            if (brake && !braking && accel < -4.5)
                d.Events.Add((t, "Hard braking"));
            braking = brake;

            int wanted = v < 1 ? 0 : v < 15 ? 1 : v < 30 ? 2 : v < 48 ? 3 : v < 68 ? 4 : v < 92 ? 5 : 6;
            if (wanted != gear && (i % (rate / 2) == 0)) gear = wanted;

            double wheelRpm = v / 3.6 / (2 * Math.PI * 0.31) * 60;
            double rpm = gear == 0 ? 820 : Math.Max(820, wheelRpm * ratios[gear]);
            rpm += 25 * Math.Sin(t * 7.1) + rng.NextDouble() * 15;

            double curve = t is > 130 and < 160 ? 0.012 : t is > 520 and < 560 ? -0.018 : 0.0025 * Math.Sin(t * 0.21);
            double steering = curve * 4200 + 4 * Math.Sin(t * 0.9) + rng.NextDouble() * 0.6;
            heading += curve * v / 3.6 / rate;
            double lat = Math.Pow(v / 3.6, 2) * curve + rng.NextDouble() * 0.05;

            d.Speed[i] = v;
            d.Rpm[i] = rpm;
            double wantedPedal = Math.Clamp(accel > 0.05 ? 14 + accel * 24 + v * 0.14 : v > 5 && !brake ? 6 + v * 0.1 : 0, 0, 100);
            pedal += (wantedPedal - pedal) * 0.05;
            d.Pedal[i] = pedal;
            d.Gear[i] = gear;
            d.Brake[i] = brake;
            d.Steering[i] = steering;
            d.LongAccel[i] = longAccel + rng.NextDouble() * 0.06 - 0.03;
            d.LatAccel[i] = lat;
        }

        d.Events.Add((255, "Highway entry"));
        d.Events.Add((470, "Highway exit"));
        d.Events.Sort();
        d.Bumps.AddRange([112.4, 118.9, 333.2, 512.6]);
        return d;
    }
}
